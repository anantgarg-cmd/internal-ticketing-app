const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync('Code.js','utf8');
const setup = fs.readFileSync('Setup.js','utf8');
const context = { console };
vm.createContext(context);
vm.runInContext(code, context);
const high = context.resolveTicketPriority_('360','SMALL_SIZED',{Priority:'HIGH',SLA_Hours:8});
const low = context.resolveTicketPriority_('360','GOLD_PLATINUM',{Priority:'LOW',SLA_Hours:24});
const regular = context.resolveTicketPriority_('Regular','',{Priority:'MEDIUM',SLA_Hours:16});
assert.deepEqual(JSON.parse(JSON.stringify(high)),{clientSize:'SMALL_SIZED',priority:'HIGH',prioritySource:'CATEGORY',slaHours:8,slaSource:'CATEGORY'});
assert.equal(low.priority,'LOW'); assert.equal(low.slaHours,24); assert.equal(low.prioritySource,'CATEGORY');
assert.equal(regular.priority,'MEDIUM'); assert.equal(regular.slaHours,16);
assert.deepEqual(context.resolveTicketPriority_('360','SMALL_SIZED',{Priority:'HIGH',SLA_Hours:8}).slaHours,context.resolveTicketPriority_('360','GOLD_PLATINUM',{Priority:'HIGH',SLA_Hours:8}).slaHours);
assert.notEqual(high.slaHours,low.slaHours);
vm.runInContext(setup.replace(/^const APP = Object\.freeze\([\s\S]*?^\}\);/m,''), context);
assert.equal(context.categorySlaHoursFromDays_(1),8);
assert.equal(context.categorySlaHoursFromDays_(2),16);
assert.equal(context.categorySlaHoursFromDays_(3),24);
assert.match(setup,/const CURRENT_SCHEMA_VERSION = 11;/);
assert.match(setup,/SCHEMA_READY_CACHE_KEY_ = 'app:schema-ready:v11'/);
assert.match(setup,/Subcategory_Name','Current_SLA_Cycle'/);
assert.match(setup,/fromVersion < 10 && toVersion >= 10/);
assert.match(code,/resolveReopenTicketPriority_\(ticket\)/);
assert.match(code,/Priority:resolution\.priority,Priority_Source:'CATEGORY',SLA_Hours:resolution\.slaHours,SLA_Source:'CATEGORY'/);
assert.match(code,/Cycle_Type:'REOPEN'/);
assert.match(code,/user\.role===APP\.ROLES\.SALES&&lower_\(ticket\.Raiser_Email\)===lower_\(user\.email\)/);
assert.match(code,/cycles\.reduce\(\(m,c\)=>Math\.max\(m,number_\(c\.Cycle_Number,0\)\),0\)\+1/);
console.log('category SLA and reopen v10 checks passed');
